def _text(value: object, default: str = "未提供") -> str:
    if value is None:
        return default
    text = str(value).strip()
    return text or default


def _year_range(series: CoinSeries) -> str:
    if series.min_year is None and series.max_year is None:
        return "未提供"
    if series.min_year == series.max_year:
        return str(series.min_year)
    if series.min_year is None:
        return f"?-{series.max_year}"
    if series.max_year is None:
        return f"{series.min_year}-?"
    return f"{series.min_year}-{series.max_year}"


